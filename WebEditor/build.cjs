const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');
const destination = path.resolve(__dirname, '../ExSticky/Markdown');
const result = esbuild.buildSync({
    absWorkingDir: __dirname, entryPoints: ['editor.js'], bundle: true, minify: true,
    outfile: path.join(destination, 'editor.js'), legalComments: 'eof', metafile: true,
    target: ['safari15']
});
const packageNames = new Set();
for (const file of Object.keys(result.metafile.inputs)) {
    const parts = file.split('node_modules/')[1]?.split('/');
    if (parts) packageNames.add(parts[0].startsWith('@') ? parts.slice(0, 2).join('/') : parts[0]);
}
let notices = 'Bundled JavaScript dependencies (generated by WebEditor/build.cjs)\n';
for (const name of [...packageNames].sort()) {
    const folder = path.join(__dirname, 'node_modules', name);
    const pkg = JSON.parse(fs.readFileSync(path.join(folder, 'package.json')));
    const license = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENSE-MIT.txt', 'license'].find(file => fs.existsSync(path.join(folder, file)));
    if (!license) throw new Error('Missing license for ' + name);
    notices += '\n' + '='.repeat(72) + '\n' + name + ' ' + pkg.version + '\n\n' + fs.readFileSync(path.join(folder, license), 'utf8') + '\n';
}
fs.writeFileSync(path.join(destination, 'THIRD-PARTY-LICENSES.txt'), notices.trimEnd() + '\n');
const katex = path.join(__dirname, 'node_modules/katex');
fs.copyFileSync(path.join(katex, 'dist/katex.min.css'), path.join(destination, 'katex.min.css'));
fs.cpSync(path.join(katex, 'dist/fonts'), path.join(destination, 'fonts'), { recursive: true });
console.log('Built offline editor and license notices.');
